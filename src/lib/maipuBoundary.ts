// La atribucion visible ya la entrega el TileLayer del mapa (GeoMapImpl.tsx).
//
// El anillo original traia 522 vertices. Aca va simplificado con
// Douglas-Peucker a una tolerancia de 0.00005 grados (~5.5 m), que lo deja en
// 210 y no se distingue del original ni a zoom de calle, con menos de la
// mitad de peso. Las coordenadas van redondeadas a 5 decimales (~1.1 m).
//
// ORDEN DE LAS COORDENADAS: [lat, lng], que es lo que espera Leaflet. GeoJSON
// las entrega al reves ([lng, lat]); la conversion ya esta hecha aca, no
// rehacerla en el consumidor.
//
// Se guarda estatico en vez de pedirselo a Nominatim en cada carga del mapa:
// un limite comunal no cambia, y una consulta de red por render seria una
// dependencia externa gratuita de romper.
// =============================================================================

